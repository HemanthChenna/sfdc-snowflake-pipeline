CREATE DATABASE IF NOT EXISTS SF_ANALYTICS;
CREATE SCHEMA   IF NOT EXISTS SF_ANALYTICS.RAW;
CREATE SCHEMA   IF NOT EXISTS SF_ANALYTICS.STAGING;
CREATE SCHEMA   IF NOT EXISTS SF_ANALYTICS.MARTS;
CREATE WAREHOUSE IF NOT EXISTS SF_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE;

-- Bronze tables: raw JSON + load metadata
CREATE TABLE IF NOT EXISTS SF_ANALYTICS.RAW.SF_ACCOUNT (
  payload VARIANT, _source_file STRING, _loaded_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS SF_ANALYTICS.RAW.SF_OPPORTUNITY (
  payload VARIANT, _source_file STRING, _loaded_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());

-- Least-privilege loader role
CREATE ROLE IF NOT EXISTS SF_LOADER;
GRANT USAGE ON WAREHOUSE SF_WH TO ROLE SF_LOADER;
GRANT USAGE ON DATABASE SF_ANALYTICS TO ROLE SF_LOADER;
GRANT ALL ON SCHEMA SF_ANALYTICS.RAW TO ROLE SF_LOADER;
